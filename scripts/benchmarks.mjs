// Benchmark circuits (ADR 0030), generated as project files so they scale with a parameter and stay in step with the
// format. Five families, each at about 1,000, 10,000 and 50,000 parts:
//   chain     a line of NOT gates from one switch to one LED
//   fanout    one switch driving many NOT gates, each with its LED
//   adder     a ripple adder of full-adder instances, one bit per row
//   counters  8-bit ripple counters of D flip-flops, all on one clock
//   cpu       copies of the reference CPU as a component (sized by copies, as each is a whole CPU)
//
//   node scripts/benchmarks.mjs           writes the 1,000-part sizes to benchmarks/ (committed)
//   node scripts/benchmarks.mjs --all     writes every size to benchmarks/generated/ (ignored by git)
//   node scripts/benchmarks.mjs --check   fails if a committed file is not what it would write
//
// Layouts are plain grids: drawable and routable, not meant to be read. Files are compact JSON, as a link carries.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const root = (path) => new URL(`../${path}`, import.meta.url);
const example = (name) => JSON.parse(readFileSync(root(`examples/${name}.clockyard.json`), "utf8"));

const part = (id, kind, x, y, props = {}, extra = {}) => ({ id, kind, position: { x, y }, rotation: 0, props, ...extra });
const wire = (id, from, to) => {
  const end = (spec) => {
    const [component, port] = spec.split(".");
    return { component, port };
  };
  return { id, from: end(from), to: end(to) };
};
const document = (name, circuit, definitions = []) => ({
  format: "clockyard",
  version: 11,
  metadata: {
    name,
    createdAt: "2026-11-16T12:00:00.000Z",
    modifiedAt: "2026-11-16T12:00:00.000Z",
    notes: "A benchmark circuit (ADR 0030), generated by scripts/benchmarks.mjs. Not meant to be read.",
  },
  circuit: { junctions: [], ...circuit },
  definitions,
});

/** `n` parts: a switch, n − 2 NOT gates in rows of 50, an LED. */
function chain(n) {
  const gates = n - 2;
  const at = (i) => [6 + (i % 50) * 5, Math.floor(i / 50) * 4];
  const components = [part("s", "switch", 0, 0)];
  const wires = [];
  for (let i = 0; i < gates; i++) {
    components.push(part(`n${i}`, "not", ...at(i)));
    wires.push(wire(`w${i}`, i === 0 ? "s.out" : `n${i - 1}.out`, `n${i}.in`));
  }
  const [x, y] = at(gates);
  components.push(part("l", "led", x, y));
  wires.push(wire("wl", `n${gates - 1}.out`, "l.in"));
  return { components, wires };
}

/** About `n` parts: one switch feeding (n − 1) / 2 NOT gates, each lighting its own LED, in rows of 40. */
function fanout(n) {
  const gates = Math.floor((n - 1) / 2);
  const components = [part("s", "switch", 0, 0)];
  const wires = [];
  for (let i = 0; i < gates; i++) {
    const [x, y] = [6 + (i % 40) * 8, Math.floor(i / 40) * 4];
    components.push(part(`n${i}`, "not", x, y), part(`l${i}`, "led", x + 4, y));
    wires.push(wire(`a${i}`, "s.out", `n${i}.in`), wire(`b${i}`, `n${i}.out`, `l${i}.in`));
  }
  return { components, wires };
}

/** About `n` parts: a carry-in switch, then per bit switches A and B, a full-adder instance and an LED; a carry-out LED. */
function adder(n) {
  const bits = Math.floor((n - 2) / 4);
  const fullAdder = example("4-bit-adder").definitions.find((d) => d.id === "full-adder");
  const at = (i) => [Math.floor(i / 100) * 40, (i % 100) * 22];
  const components = [part("cin", "switch", 0, -6)];
  const wires = [];
  for (let i = 0; i < bits; i++) {
    const [x, y] = at(i);
    components.push(
      part(`a${i}`, "switch", x, y),
      part(`b${i}`, "switch", x, y + 6),
      part(`fa${i}`, "custom", x + 10, y, {}, { definition: "full-adder" }),
      part(`s${i}`, "led", x + 32, y + 6),
    );
    wires.push(
      wire(`wa${i}`, `a${i}.out`, `fa${i}.a`),
      wire(`wb${i}`, `b${i}.out`, `fa${i}.b`),
      wire(`wc${i}`, i === 0 ? "cin.out" : `fa${i - 1}.cout`, `fa${i}.cin`),
      wire(`ws${i}`, `fa${i}.s`, `s${i}.in`),
    );
  }
  const [x, y] = at(bits);
  components.push(part("cout", "led", x + 32, y));
  wires.push(wire("wcout", `fa${bits - 1}.cout`, "cout.in"));
  return { circuit: { components, wires }, definitions: [fullAdder] };
}

/** About `n` parts: one clock, and 8-bit ripple counters (a D flip-flop and a NOT per bit) each with an LED on bit 7. */
function counters(n) {
  const count = Math.floor((n - 1) / 17);
  const components = [part("clk", "clock", 0, 0)];
  const wires = [];
  for (let c = 0; c < count; c++) {
    const [x0, y0] = [6 + Math.floor(c / 50) * 80, c * 10 - Math.floor(c / 50) * 500];
    for (let b = 0; b < 8; b++) {
      const [x, y] = [x0 + b * 8, y0];
      components.push(part(`c${c}q${b}`, "dff", x, y), part(`c${c}n${b}`, "not", x, y + 5));
      wires.push(
        wire(`c${c}d${b}`, `c${c}n${b}.out`, `c${c}q${b}.d`),
        wire(`c${c}f${b}`, `c${c}q${b}.q`, `c${c}n${b}.in`),
        // Each bit is clocked by the one below: a ripple counter, counting down from 0 by one per clock rise.
        wire(`c${c}k${b}`, b === 0 ? "clk.out" : `c${c}q${b - 1}.q`, `c${c}q${b}.clk`),
      );
    }
    components.push(part(`c${c}l`, "led", x0 + 66, y0));
    wires.push(wire(`c${c}o`, `c${c}q7.q`, `c${c}l.in`));
  }
  return { components, wires };
}

/** `copies` instances of the reference CPU, made a component: its ROM, RAM, devices and clock run inside each. */
function cpu(copies) {
  const reference = example("reference-cpu");
  // The program's assembly source is the editor's only; its words are what the ROM holds.
  const circuit = {
    ...reference.circuit,
    components: reference.circuit.components.map(({ props: { source: _source, ...props }, ...c }) => ({ ...c, props })),
  };
  const definition = { id: "cpu", name: "Reference CPU", circuit };
  const components = Array.from({ length: copies }, (_, i) => part(`cpu${i}`, "custom", (i % 10) * 12, Math.floor(i / 10) * 24, {}, { definition: "cpu" }));
  return { circuit: { components, wires: [] }, definitions: [definition, ...reference.definitions] };
}

const SIZES = { "1k": 1000, "10k": 10000, "50k": 50000 };
// Copies of the CPU for about as many engine nets as the other families have parts: one CPU is about 300.
const CPU_COPIES = { "1k": 4, "10k": 34, "50k": 170 };

function build(family, size) {
  const name = `${family}-${size}`;
  if (family === "cpu") {
    const { circuit, definitions } = cpu(CPU_COPIES[size]);
    return document(name, circuit, definitions);
  }
  if (family === "adder") {
    const { circuit, definitions } = adder(SIZES[size]);
    return document(name, circuit, definitions);
  }
  // 50,000 parts of counters, with three wires a bit, would pass Import's 10 MB limit (a finding of its own, in
  // docs/performance.md): that size is held to 44,000.
  const parts = family === "counters" && size === "50k" ? 44000 : SIZES[size];
  return document(name, { chain, fanout, counters }[family](parts));
}

const FAMILIES = ["chain", "fanout", "adder", "counters", "cpu"];
const all = process.argv.includes("--all");
const check = process.argv.includes("--check");
const dir = all ? "benchmarks/generated" : "benchmarks";
mkdirSync(root(dir), { recursive: true });
let stale = 0;
for (const family of FAMILIES) {
  for (const size of all ? Object.keys(SIZES) : ["1k"]) {
    const path = `${dir}/${family}-${size}.clockyard.json`;
    const doc = build(family, size);
    const text = `${JSON.stringify(doc)}\n`;
    if (check) {
      let current = "";
      try {
        current = readFileSync(root(path), "utf8").replaceAll("\r\n", "\n");
      } catch {
        // Missing counts as stale.
      }
      if (current !== text) {
        console.error(`${path} is not what scripts/benchmarks.mjs writes; run it and commit the result.`);
        stale++;
      }
      continue;
    }
    writeFileSync(root(path), text);
    console.log(`${path}: ${doc.circuit.components.length} parts, ${doc.circuit.wires.length} wires, ${(text.length / 1024).toFixed(0)} KB`);
  }
}
if (stale > 0) process.exit(1);
